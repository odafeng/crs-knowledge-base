import { pageMetadata, paperJsonLd } from "@/lib/seo";
import type { Metadata } from "next";
import Link from "next/link";
import { DataFigure } from "@/components/news-figure";
import { GlanceFinding, PaperGlance } from "@/components/paper-summary";
import { ReviewActions } from "@/components/review-actions";
import { extractPaperFigures } from "@/lib/paper-figures";
import { needsReview } from "@/lib/review";
import { ReaderComments } from "@/components/comments";
import { notFound } from "next/navigation";
import {
  AiChip,
  Breadcrumb,
  Icon,
  PaperCard,
  PaperMeta,
  RichHtml,
  JsonLd,
} from "@/components/reading";
import {
  getPaperBySlug,
  listNews,
  listPapers,
  listTopics,
} from "@/lib/content";
import {
  byTopic,
  cleanPaperDetailHtml,
  COMMENTARY_LABELS,
  commentaryOf,
  doiUrl,
  extractPmid,
  isUnreviewed,
  MCRC,
  newsPath,
  paperPath,
  paperTitle,
  SOURCE_LABELS,
  topicPath,
} from "@/lib/site";

export const revalidate = 3600;
// Paths are rendered on first request and then regenerated by ISR; the build never calls the API.
export async function generateStaticParams() {
  return [];
}

type Props = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const paper = await getPaperBySlug((await params).slug);
  return paper
    ? pageMetadata(paperTitle(paper), paper.bottomLine, paperPath(paper), {
        indexable: !isUnreviewed(paper),
        type: "article",
      })
    : {};
}

export default async function PaperPage({ params }: Props) {
  const paper = await getPaperBySlug((await params).slug);
  if (!paper) notFound();
  const [papers, news, topics] = await Promise.all([
    listPapers(),
    listNews(),
    listTopics(),
  ]);
  const topic = topics.find((t) => t.key === paper.topic);
  const related = byTopic(papers, paper.topic)
    .filter((p) => p.id !== paper.id)
    .slice(0, 4);
  const stories = news.filter((item) => item.paperId === paper.id);
  const storyWithFigures = stories.find((item) => item.figures.length > 0);
  const paperFigures = storyWithFigures
    ? storyWithFigures.figures
    : extractPaperFigures(paper);
  const figureCaption = storyWithFigures
    ? storyWithFigures.figureNote
    : `依本頁條目數據繪製（來源：${paper.journal} ${paper.year}），完整數據與亞組分析請見原文。`;
  const commentary = commentaryOf(paper);
  const summary = paper.summary;
  const summaryPending = summary?.reviewedAt === null;
  const detailHtml = paper.detailHtml
    ? cleanPaperDetailHtml(paper.detailHtml)
    : "";
  const pmid = paper.detailHtml ? extractPmid(paper.detailHtml) : null;
  const crumbs = [
    ...MCRC,
    ...(topic ? ([[topic.label, topicPath(topic)]] as const) : []),
    [paper.regimen, paperPath(paper)] as const,
  ];

  return (
    <div className="container page">
      <JsonLd data={paperJsonLd(paper, topic, crumbs)} />
      <Breadcrumb crumbs={crumbs} />
      <article className="split">
        <div>
          <header
            className={
              summary ? "story__head story__head--glance" : "story__head"
            }
          >
            <PaperMeta paper={paper} topic={topic} />
            <h1>{summary?.title ?? paper.regimen}</h1>
          </header>
          {summary && <GlanceFinding summary={summary} />}
          {(isUnreviewed(paper) || summaryPending) && (
            <div className="callout callout--ai" role="note">
              <Icon name="info" />
              <p>
                {isUnreviewed(paper)
                  ? "這一頁由 AI 依摘要整理，尚未經人工審核。"
                  : "上面的速覽由 AI 依摘要整理，尚未經人工審核。"}
                數字已逐一比對摘要原文，但解讀可能有誤，請以原文為準。
              </p>
            </div>
          )}
          {needsReview(paper) && (
            <ReviewActions kind="paper" target={paper.id} />
          )}
          {summary ? (
            <>
              {paperFigures.length > 0 && (
                <DataFigure
                  figures={paperFigures}
                  title="試驗關鍵數據"
                  caption={figureCaption}
                  className="paper-figure"
                />
              )}
              <PaperGlance summary={summary} topic={topic} />
            </>
          ) : (
            <>
              <div className="paper-brief">
                <p className="result">
                  <span className="result__label">關鍵結果</span>
                  {paper.result}
                </p>
                <p className="bottom-line">{paper.bottomLine}</p>
              </div>
              {paperFigures.length > 0 && (
                <DataFigure
                  figures={paperFigures}
                  title="試驗關鍵數據"
                  caption={figureCaption}
                  className="paper-figure"
                />
              )}
            </>
          )}
          {(summary || detailHtml) && (
            <details className="page__section source-details" open={!summary}>
              <summary>
                <h2>{summary ? "原始條目與原文摘要" : "詳細證據整理"}</h2>
              </summary>
              {summary && (
                <>
                  <p className="result">
                    <span className="result__label">關鍵結果（原始條目）</span>
                    {paper.result}
                  </p>
                  <p className="bottom-line">{paper.bottomLine}</p>
                </>
              )}
              {detailHtml && (
                <RichHtml html={detailHtml} label="詳細證據整理，可左右捲動" />
              )}
            </details>
          )}
          {commentary.length > 0 && (
            <section className="page__section" aria-labelledby="commentary">
              <h2 id="commentary">相關評論</h2>
              <ul className="entries">
                {commentary.map((c) => (
                  <li className="entry" key={c.doi ?? c.pmid ?? c.title}>
                    <p className="eyebrow">
                      <span>{COMMENTARY_LABELS[c.type] ?? c.type}</span>
                      <span>
                        {c.journal} {c.year ?? ""}
                      </span>
                      {isUnreviewed(c) && <AiChip label="AI 未審" />}
                    </p>
                    <h3 className="entry__title">
                      {c.doi ? (
                        <a href={doiUrl(c.doi)} rel="noopener">
                          {c.title}
                        </a>
                      ) : (
                        c.title
                      )}
                    </h3>
                    <p className="entry__line">{c.summary}</p>
                  </li>
                ))}
              </ul>
            </section>
          )}
          <ReaderComments paperId={paper.id} />
        </div>
        <aside className="split__rail" aria-label="研究資料與連結">
          <dl className="facts">
            <dt>期刊</dt>
            <dd>
              {paper.journal} {paper.year}
            </dd>
            <dt>研究設計</dt>
            <dd>{paper.studyType}</dd>
            {paper.n !== null && paper.n !== undefined && paper.n !== "" && (
              <>
                <dt>收案數</dt>
                <dd>{paper.n}</dd>
              </>
            )}
            <dt>主要指標</dt>
            <dd>{paper.endpoint}</dd>
            <dt>資料來源</dt>
            <dd>{SOURCE_LABELS[paper.source]}</dd>
            {pmid && (
              <>
                <dt>PMID</dt>
                <dd>
                  <a
                    href={`https://pubmed.ncbi.nlm.nih.gov/${pmid}/`}
                    rel="noopener"
                  >
                    {pmid}
                  </a>
                </dd>
              </>
            )}
            <dt>最近複查</dt>
            <dd>
              <time dateTime={paper.reviewedAt}>{paper.reviewedAt}</time>
            </dd>
          </dl>
          <div className="actions actions--rail">
            {paper.doi && (
              <a
                className="btn btn--primary"
                href={doiUrl(paper.doi)}
                rel="noopener"
              >
                <Icon name="external" />
                看原文（DOI）
              </a>
            )}
            {stories.map((item) => (
              <Link
                className="btn btn--secondary"
                href={newsPath(item)}
                key={item.id}
              >
                <Icon name="news" />
                讀這篇的消息
              </Link>
            ))}
          </div>
        </aside>
      </article>
      {related.length > 0 && topic && (
        <section className="page__section" aria-labelledby="related">
          <h2 id="related">同主題的其他文獻</h2>
          <ul className="paper-list">
            {related.map((p) => (
              <PaperCard paper={p} key={p.id} />
            ))}
          </ul>
          <p className="page__more">
            <Link href={topicPath(topic)}>看 {topic.label} 的全部文獻</Link>
          </p>
        </section>
      )}
    </div>
  );
}
